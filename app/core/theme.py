def _theme_variant(
    base: str,
    name: str,
    mode: str,
    *,
    bg: str,
    panel: str,
    text: str,
    muted: str,
    primary: str,
    accent: str,
    preview_bg: str,
    preview_grid: str,
    preview_ink: str,
    hero_one: str,
    hero_two: str,
    bg_blur: str,
) -> dict:
    """复制一个基础主题，只替换 UI 层颜色。"""
    item = dict(THEMES[base])
    item.update(
        {
            "name": name,
            "mode": mode,
            "bg": bg,
            "panel": panel,
            "text": text,
            "muted": muted,
            "primary": primary,
            "accent": accent,
            "preview_bg": preview_bg,
            "preview_grid": preview_grid,
            "preview_ink": preview_ink,
            "hero_one": hero_one,
            "hero_two": hero_two,
            "bg_blur": bg_blur,
        }
    )
    return item


