PALETTE_AUTO = "Auto"


def _lighten(hex_color: str, amount: float = 0.12) -> str:
    """把颜色朝白色插值 amount，用于暗色主题下保持可辨识度。"""
    raw = hex_color.lstrip("#")
    r, g, b = (int(raw[index:index + 2], 16) for index in (0, 2, 4))
    r, g, b = (round(value + (255 - value) * amount) for value in (r, g, b))
    return f"#{r:02X}{g:02X}{b:02X}"


def _luminance(hex_color: str) -> float:
    raw = hex_color.lstrip("#")
    channels = [int(raw[index:index + 2], 16) / 255 for index in (0, 2, 4)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def _usable(colors: list[str]) -> list[str]:
    """近乎纯白的颜色做数据填充会看不见（深色是色板刻意选的，保留）。"""
    picked = [c for c in colors if _luminance(c) <= 0.82]
    return picked if len(picked) >= 2 else colors


def apply_sci_theme(palette_id: str = PALETTE_AUTO) -> None:
    """把 SCI 配色应用到 10 套主题（原地修改 THEMES，可重复调用）。

    ``palette_id`` 为 ``"Auto"`` 时保持各模块自己的 SCI 语义色（默认行为）；
    指定 ``No.001`` 等色板编号时，用该色板覆盖分组/分类色。
    """
    # 1) 从基线恢复，保证幂等
    for name, base in _BASE_THEMES.items():
        THEMES[name].clear()
        THEMES[name].update(copy.deepcopy(base))

    # 2) 语义色：固定的数据色 + 可切换的分类色（先都填语义默认值）
    for _name, _theme in THEMES.items():
        factor = 0.12 if _theme.get("mode") == "dark" else 0.0
        _theme.update(
            {
                key: (_lighten(value, factor) if factor else value)
                for key, value in SCI_ALL_SEMANTIC.items()
            }
        )
        if _theme.get("mode") == "dark":
            # 热图发散色阶两端在深色底上需要更亮：高端 #571925 → #B05A6A，
            # 低端同步提亮，否则 colorbar 两端贴着深色背景几乎看不到
            _theme["heatmap_high"] = "#B05A6A"
            _theme["heatmap_low"] = _lighten("#669DBC", 0.18)
            # GMP 空单元格：浅色 #F0EAE1 在深底上会变成刺眼白块，
            # 换成比面板略亮的灰紫，既能看见格子边界又不抢眼
            _theme["gmp_empty"] = "#3A3A4A"
            _theme["gmp_border"] = "#6B7280"

    # 3) 指定色板：循环取色覆盖分类色（语义色不变）
    if palette_id and palette_id != PALETTE_AUTO:
        colors = _usable(list(SCI_PALETTES.get(palette_id) or SCI_PALETTES["No.002"]))
        for _name, _theme in THEMES.items():
            factor = 0.12 if _theme.get("mode") == "dark" else 0.0
            for group in CATEGORICAL_GROUPS:
                for index, key in enumerate(group):
                    color = colors[index % len(colors)]
                    _theme[key] = _lighten(color, factor) if factor else color


# 默认行为与之前完全一致
apply_sci_theme(PALETTE_AUTO)
